"$PY" - <<'PY' || die "Quranpedia dump could not be fetched or verified (see above)."
import hashlib, json, os, shutil, sys, time, urllib.request, zipfile

ROOT = os.environ["MIZAN_ROOT"]
UA = os.environ["MIZAN_UA"]
OFFLINE = os.environ["MIZAN_OFFLINE"] == "1"
PER_FILE = os.environ["MIZAN_PER_FILE"] == "1"
ACCEPT_NEW = os.environ.get("MIZAN_ACCEPT_NEW_DUMP") == "1"
RAW = os.path.join(ROOT, "data", "raw")
OUT = os.path.join(RAW, "quranpedia")
MANIFEST = os.path.join(RAW, "manifest.json")
ZIP = os.path.join(RAW, "translations-all.zip")
DUMPS, HOST = os.environ["QP_DUMPS"], os.environ["QP_HOST"]

pinned = {}
for line in os.environ["QP_PINNED"].strip().splitlines():
    sha, name, lang = line.split()
    pinned[name] = (sha, lang)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def download(url, dest, label, gzip_ok=False):
    """Stream to dest.part, then rename. Three attempts, loud on failure."""
    if OFFLINE:
        sys.exit(f"  --offline, and {os.path.relpath(dest, ROOT)} is not cached")
    headers = {"User-Agent": UA}
    if gzip_ok:
        headers["Accept-Encoding"] = "gzip"
    last = None
    for attempt in range(1, 4):
        try:
            req = urllib.request.Request(url, headers=headers)
            with urllib.request.urlopen(req, timeout=120) as r:
                total = int(r.headers.get("Content-Length") or 0)
                gz = r.headers.get("Content-Encoding") == "gzip"
                tmp = dest + ".part"
                got, t0, shown = 0, time.time(), 0
                with open(tmp, "wb") as fh:
                    while True:
                        chunk = r.read(1 << 16)
                        if not chunk:
                            break
                        fh.write(chunk)
                        got += len(chunk)
                        if total > 8_000_000 and got - shown >= 8_000_000:
                            shown = got
                            print(f"        {label}: {got/1e6:5.1f} / {total/1e6:.1f} MB "
                                  f"({got/1e6/max(time.time()-t0, 1e-6):.1f} MB/s)", flush=True)
            if gz:
                import gzip
                with gzip.open(tmp, "rb") as src, open(tmp + ".u", "wb") as dst:
                    shutil.copyfileobj(src, dst)
                os.replace(tmp + ".u", tmp)
            if total and not gz and got != total:
                raise IOError(f"short read {got} of {total} bytes")
            os.replace(tmp, dest)
            return
        except Exception as exc:                                  # noqa: BLE001
            last = exc
            print(f"  warn  {label}: attempt {attempt} failed: {exc}", flush=True)
            time.sleep(3 * attempt)
    sys.exit(f"  could not download {url}: {last}")


def verify(name):
    """None if the extracted file is exactly the pinned one, else the reason."""
    path = os.path.join(OUT, name)
    if not os.path.exists(path):
        return "missing"
    got = sha256(path)
    if got != pinned[name][0]:
        return f"sha256 {got[:16]}… != pinned {pinned[name][0][:16]}…"
    return None


# -- 1. manifest -------------------------------------------------------------
need = [n for n in pinned if verify(n)]
if not os.path.exists(MANIFEST) or (need and not OFFLINE):
    download(f"{DUMPS}/manifest.json", MANIFEST, "manifest.json")
manifest = json.load(open(MANIFEST, encoding="utf-8"))
version = manifest.get("version", "?")
books = {b["name"]: b for b in manifest.get("translation_books", [])}
print(f"  ok    manifest.json · dump version {version} · "
      f"{len(books)} translation books listed")

# -- 2. the 22 files ---------------------------------------------------------
if not need:
    print(f"  ok    all {len(pinned)} pinned translations already present and verified "
          f"(cached, nothing downloaded)")
else:
    print(f"  ..    {len(need)} of {len(pinned)} translation files to fetch")
    if PER_FILE:
        for name in need:
            url = books.get(name, {}).get("url") or f"{HOST}/translation-books/{name}"
            url = url.replace("http://localhost", HOST)   # the manifest's URLs are wrong
            download(url, os.path.join(OUT, name), name, gzip_ok=True)
            time.sleep(0.5)
    else:
        zip_ok = False
        if os.path.exists(ZIP):
            try:
                with zipfile.ZipFile(ZIP) as z:
                    zip_ok = all(n in z.namelist() for n in need)
            except zipfile.BadZipFile:
                zip_ok = False
        if not zip_ok:
            size = (manifest.get("archives", {}).get("translations", {}) or {}).get("bytes")
            print(f"  ..    downloading translations-all.zip"
                  + (f" ({size/1e6:.0f} MB)" if size else ""), flush=True)
            download(f"{DUMPS}/translations-all.zip", ZIP, "translations-all.zip")
        with zipfile.ZipFile(ZIP) as z:
            for name in need:
                # ZipFile.read() checks each member's CRC-32 and raises on damage.
                data = z.read(name)
                with open(os.path.join(OUT, name), "wb") as fh:
                    fh.write(data)
            if "LICENSE.md" in z.namelist():
                with open(os.path.join(OUT, "LICENSE.md"), "wb") as fh:
                    fh.write(z.read("LICENSE.md"))
        print(f"  ok    extracted {len(need)} files from translations-all.zip "
              f"(CRC-32 checked)")

# -- 3. verify every file, twice ----------------------------------------------
bad = []
for name, (sha, lang) in sorted(pinned.items(), key=lambda kv: int(kv[0].split(".")[0])):
    path = os.path.join(OUT, name)
    size = os.path.getsize(path) if os.path.exists(path) else -1
    listed = books.get(name)
    if listed is None:
        bad.append(f"{name}: not listed in manifest {version}")
        continue
    if listed.get("bytes") != size:
        bad.append(f"{name}: {size} bytes, manifest {version} says {listed.get('bytes')}")
        continue
    why = verify(name)
    if why:
        if ACCEPT_NEW:
            print(f"  warn  {name}: {why} — accepted (MIZAN_ACCEPT_NEW_DUMP=1)")
        else:
            bad.append(f"{name}: {why}")
            # Quarantine it so nothing can index it by accident.
            os.replace(path, path + ".rejected")
        continue
    print(f"  ok    {name:11s} {lang}  {size:>10,} B  sha256 {sha[:12]}…  "
          f"{listed.get('title', '')[:40]}")
extra = sorted(f for f in os.listdir(OUT) if f.endswith(".json") and f not in pinned)
if extra:
    bad.append(f"unexpected files in data/raw/quranpedia/ would be indexed: {extra}")
if bad:
    print("\n  CHECKSUM / MANIFEST MISMATCH — refusing to build an index from these files:")
    for b in bad:
        print(f"    - {b}")
    print("\n  If Quranpedia corrected a translation, that is expected over time: re-run"
          "\n  with MIZAN_ACCEPT_NEW_DUMP=1, then re-measure (`make eval`) and update the"
          "\n  pins in scripts/setup.sh. Never publish old numbers against new text.")
    sys.exit(1)
print(f"  ok    {len(pinned)}/{len(pinned)} verified: size = manifest, SHA-256 = pinned "
      f"(pins from dump {os.environ['QP_PINNED_VERSION']}, current dump {version})")
PY

