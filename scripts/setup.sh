#!/usr/bin/env bash
# =============================================================================
# MIZAN — one-command setup from a clean clone.
#
#     ./scripts/setup.sh                 # or: make setup
#
# Builds data/corpus.sqlite (≈124 MB, too large for GitHub, so never committed)
# from the publishers' own official files, verifying every byte on the way:
#
#   1. Quranpedia.net official dump — https://quranpedia.net/dumps/
#        manifest.json + translations-all.zip, then the 22 approved
#        translations MIZAN indexes are extracted and checked twice:
#          * byte size  against the publisher's manifest (translation_books[])
#          * SHA-256    against the values pinned below (the exact content every
#                       published number was measured on)
#   2. Tanzil Quran text (Uthmani + simple-clean) — https://tanzil.net
#        verse lines checked against pinned SHA-256 values.
#   3. scripts/build_index.py, then scripts/fetch_arabic.py.
#   4. The finished index is fingerprinted (python3 -m mizan.eval --check-index)
#      and must equal the reference index the evaluation was run on.
#   5. The redistributable terminology glossary is checked (or regenerated by
#      scripts/export_public_glossary.py when the full local copy exists).
#
# Idempotent: every step is cached under data/raw/ and skipped when its output
# already verifies. A second run downloads nothing and rebuilds nothing.
# Fails loudly — non-zero exit, a message naming the file — on any mismatch.
#
# Options
#   --offline       never touch the network; use data/raw/ only
#   --force         rebuild the index even if it already verifies
#   --per-file      fetch the 22 translation files individually from the dump
#                   host instead of the 64 MB zip (faster; same bytes)
#   --real-corpus   also rebuild data/real/ from the publishers' pages
#                   (scripts/rebuild_real_corpus.py; ~10 min, polite crawl)
#   --no-changes    skip the Quranpedia "changes since" courtesy check
#   -h | --help
#
# Environment
#   PYTHON                         interpreter (default: python3, must be >= 3.11)
#   MIZAN_ALLOW_INDEX_DRIFT=1      warn instead of fail if the built index does
#                                  not match the reference fingerprint
#   MIZAN_ACCEPT_NEW_DUMP=1        accept translation files whose SHA-256 differs
#                                  from the pins (publisher corrected the text).
#                                  Every published number must then be re-measured.
#
# Network etiquette: Quranpedia's usage policy forbids bulk API scraping and
# asks high-volume clients to put a contact address in the User-Agent. We use
# only the official dumps (plus one optional call to the changes endpoint the
# policy itself recommends), sequentially, with the UA below.
# =============================================================================
