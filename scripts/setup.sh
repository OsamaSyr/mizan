step 3/7 "Tanzil Quran text (Arabic source, verbatim)"
# =============================================================================
"$PY" - <<'PY' || die "Tanzil text could not be fetched or verified (see above)."
import hashlib, os, sys, time, urllib.parse, urllib.request

ROOT = os.environ["MIZAN_ROOT"]
OFFLINE = os.environ["MIZAN_OFFLINE"] == "1"
CACHE = os.path.join(ROOT, "data", "raw", "tanzil")
pinned = {}
for line in os.environ["TANZIL_PINNED"].strip().splitlines():
    sha, ed = line.split()
    pinned[ed] = sha


def verse_sha(path):
    text = open(path, encoding="utf-8").read()
    lines = [ln for ln in text.splitlines() if ln.strip() and not ln.startswith("#")]
    return hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest(), len(lines)


for ed, want in pinned.items():
    path = os.path.join(CACHE, f"{ed}.txt")
    if os.path.exists(path) and verse_sha(path)[0] == want:
        print(f"  ok    {ed:13s} cached and verified")
        continue
    if OFFLINE:
        sys.exit(f"  --offline, and {ed} is missing or does not verify")
    body = urllib.parse.urlencode(
        {"quranType": ed, "outType": "txt-2", "agree": "true"}).encode()
    req = urllib.request.Request(os.environ["TANZIL_URL"], data=body,
                                 headers={"User-Agent": os.environ["MIZAN_UA"]})
    with urllib.request.urlopen(req, timeout=120) as r:
        raw = r.read().decode("utf-8")
    with open(path + ".part", "w", encoding="utf-8") as fh:
        fh.write(raw)
    got, n = verse_sha(path + ".part")
    if got != want:
        sys.exit(f"  {ed}: {n} verse lines, sha256 {got[:16]}… != pinned {want[:16]}…\n"
                 f"  Tanzil may have published a correction; refusing to continue.")
    os.replace(path + ".part", path)
    print(f"  ok    {ed:13s} downloaded · {n:,} verse lines · sha256 = pinned")
    time.sleep(1)
PY

